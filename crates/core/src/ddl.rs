    /// Re-reading a created table gives the same structure, and edits read back as is (FKs · indexes · defaults · comments · auto-increment)
    async fn round_trip(kind: DbKind, schema: &str) {
        let Some(st) = state(kind).await else { return };
        let q = |s: &str| st.run_query("d".into(), s.into(), None, None);
        q("drop table if exists qd_items").await.unwrap();
        q("drop table if exists qd_members").await.unwrap();
        q("drop table if exists qd_users").await.unwrap();
        let int = if kind == DbKind::Mysql { "int" } else { "integer" };
        let users = TableDef {
            schema: schema.into(),
            name: "qd_users".into(),
            columns: vec![
                ColumnDef { name: "id".into(), data_type: int.into(), auto_increment: true, ..Default::default() },
                ColumnDef { name: "email".into(), data_type: "varchar(100)".into(), ..Default::default() },
                ColumnDef { name: "status".into(), data_type: "varchar(10)".into(), nullable: true, default: Some("'active'".into()), comment: Some("state".into()), ..Default::default() },
            ],
            primary_key: vec!["id".into()],
            indexes: vec![IndexDef { name: "qd_users_email".into(), columns: vec!["email".into()], unique: true, ..Default::default() }],
            comment: Some("people".into()),
            ..Default::default()
        };
        st.run_ddl("d".into(), st.table_ddl("d".into(), None, users.clone()).unwrap()).await.unwrap();
        let items = TableDef {
            schema: schema.into(),
            name: "qd_items".into(),
            columns: vec![ColumnDef { name: "id".into(), data_type: int.into(), ..Default::default() }, ColumnDef { name: "user_id".into(), data_type: int.into(), nullable: true, ..Default::default() }],
            primary_key: vec!["id".into()],
            foreign_keys: vec![ForeignKeyDef { name: "qd_items_user".into(), columns: vec!["user_id".into()], ref_schema: schema.into(), ref_table: "qd_users".into(), ref_columns: vec!["id".into()], on_delete: "CASCADE".into(), ..Default::default() }],
            ..Default::default()
        };
        st.run_ddl("d".into(), st.table_ddl("d".into(), None, items).unwrap()).await.unwrap();
        let got = st.table_def("d".into(), schema.into(), "qd_users".into()).await.unwrap();
        assert_eq!(got.columns.iter().map(|c| (c.name.as_str(), c.nullable, c.auto_increment)).collect::<Vec<_>>(), vec![("id", false, true), ("email", false, false), ("status", true, false)]);
        assert_eq!(got.columns[2].default.as_deref().map(|d| d.split("::").next().unwrap()), Some("'active'"));
        assert_eq!((got.columns[2].comment.as_deref(), got.comment.as_deref()), (Some("state"), Some("people")));
        assert_eq!(got.primary_key, vec!["id"]);
        assert_eq!(got.indexes.iter().map(|i| (i.name.as_str(), i.unique, i.columns.clone())).collect::<Vec<_>>(), vec![("qd_users_email", true, vec!["email".to_string()])]);
        // Nothing to change if as read
        assert!(st.table_ddl("d".into(), Some(got.clone()), got.clone()).unwrap().is_empty(), "{:?}", st.table_ddl("d".into(), Some(got.clone()), got.clone()));
        let fk = st.table_def("d".into(), schema.into(), "qd_items".into()).await.unwrap();
        assert_eq!((fk.foreign_keys.len(), fk.foreign_keys[0].on_delete.as_str(), fk.foreign_keys[0].ref_table.as_str()), (1, "CASCADE", "qd_users"));
        assert!(st.table_ddl("d".into(), Some(fk.clone()), fk.clone()).unwrap().is_empty());
        // Modify: name · column name · type · NOT NULL · default · new column · index change
        q("insert into qd_users (email) values ('a@x.com')").await.unwrap();
        let mut after = got.clone();
        after.name = "qd_members".into();
        after.columns[1].name = "mail".into();
        after.columns[1].data_type = "varchar(200)".into();
        after.columns[2].nullable = false;
        after.columns[2].default = Some("'new'".into());
        after.columns.push(ColumnDef { name: "age".into(), data_type: int.into(), nullable: true, ..Default::default() });
        after.indexes[0] = IndexDef { name: "qd_members_mail".into(), columns: vec!["mail".into()], unique: false, ..Default::default() };
        let ddl = st.table_ddl("d".into(), Some(got), after.clone()).unwrap();
        st.run_ddl("d".into(), ddl.clone()).await.unwrap();
        let now = st.table_def("d".into(), schema.into(), "qd_members".into()).await.unwrap();
        assert_eq!(now.columns.iter().map(|c| c.name.as_str()).collect::<Vec<_>>(), vec!["id", "mail", "status", "age"], "{ddl:?}");
        assert!(now.columns[1].data_type.contains("200") && !now.columns[2].nullable);
        assert_eq!(now.indexes.iter().map(|i| (i.name.as_str(), i.unique)).collect::<Vec<_>>(), vec![("qd_members_mail", false)]);
        assert_eq!(q("select mail from qd_members").await.unwrap().rows[0][0], serde_json::json!("a@x.com"));
        // FKs still point to the renamed table
        assert_eq!(st.table_def("d".into(), schema.into(), "qd_items".into()).await.unwrap().foreign_keys[0].ref_table, "qd_members");
        q("drop table qd_items").await.unwrap();
        q("drop table qd_members").await.unwrap();
    }

