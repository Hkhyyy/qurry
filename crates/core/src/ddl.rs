//! 객체 만들기 · 고치기 (DataGrip 우클릭 › New ▸ · Modify Table… · Rename…): PostgreSQL · MySQL.
//! 테이블은 구조 (TableDef) 를 읽어 와서 화면에서 고친 것과 비교해 ALTER 문장을 만든다. 만들기는 before 없이 CREATE.
//! 문장은 미리 보여 주고 실행한다 (PG 는 한 트랜잭션 — DDL 도 되돌릴 수 있다. MySQL 은 문장마다 바로 반영된다)
use crate::app::{AppState, ensure_pool};
use crate::db::Pool;
use crate::error::{AppError, AppResult};
use crate::store::DbKind;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ColumnDef {
    pub name: String,
    /// 지금 DB 에 있는 이름 (없으면 새 컬럼)
    #[serde(default)]
    pub orig: Option<String>,
    pub data_type: String,
    #[serde(default)]
    pub nullable: bool,
    /// SQL 식 그대로 ('active', 0, now() …)
    #[serde(default)]
    pub default: Option<String>,
    /// PG identity (GENERATED BY DEFAULT AS IDENTITY) · MySQL AUTO_INCREMENT
    #[serde(default)]
    pub auto_increment: bool,
    #[serde(default)]
    pub comment: Option<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct IndexDef {
    pub name: String,
    #[serde(default)]
    pub orig: Option<String>,
    pub columns: Vec<String>,
    #[serde(default)]
    pub unique: bool,
    /// UNIQUE 제약으로 만든 것 (지울 때 DROP CONSTRAINT)
    #[serde(default)]
    pub constraint: bool,
    /// 식 · 조건이 있는 인덱스: 고칠 수 없고 지우기만 (정의 글)
    #[serde(default)]
    pub definition: Option<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ForeignKeyDef {
    pub name: String,
    #[serde(default)]
    pub orig: Option<String>,
    pub columns: Vec<String>,
    #[serde(default)]
    pub ref_schema: String,
    pub ref_table: String,
    pub ref_columns: Vec<String>,
    /// NO ACTION · RESTRICT · CASCADE · SET NULL · SET DEFAULT
    #[serde(default)]
    pub on_delete: String,
    #[serde(default)]
    pub on_update: String,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TableDef {
    pub schema: String,
    pub name: String,
    pub columns: Vec<ColumnDef>,
    #[serde(default)]
    pub primary_key: Vec<String>,
    /// 지금 PK 제약 이름 (PG 에서 지울 때)
    #[serde(default)]
    pub primary_key_name: Option<String>,
    #[serde(default)]
    pub indexes: Vec<IndexDef>,
    #[serde(default)]
    pub foreign_keys: Vec<ForeignKeyDef>,
    #[serde(default)]
    pub comment: Option<String>,
}

/// New ▸ 의 단순한 객체
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum NewObject {
    /// PG: encoding (UTF8 …) · MySQL: charset (utf8mb4 …)
    Database { name: String, #[serde(default)] charset: String },
    Schema { name: String },
    View { schema: String, name: String, query: String, #[serde(default)] materialized: bool },
    Sequence { schema: String, name: String, #[serde(default)] start: Option<i64>, #[serde(default)] increment: Option<i64> },
}

fn q(kind: DbKind, s: &str) -> String {
    crate::sql::quote_ident(kind, s)
}

fn rel(kind: DbKind, schema: &str, name: &str) -> String {
    crate::fake::qualified(kind, schema, name)
}

fn lit(kind: DbKind, s: &str) -> String {
    crate::transfer::sql_literal(kind, &serde_json::Value::String(s.into()))
}

fn list(kind: DbKind, cols: &[String]) -> String {
    cols.iter().map(|c| q(kind, c)).collect::<Vec<_>>().join(", ")
}

/// 컬럼 정의 한 줄 (CREATE TABLE 안 · MySQL CHANGE COLUMN)
fn column_sql(kind: DbKind, c: &ColumnDef) -> String {
    let mut s = format!("{} {}", q(kind, &c.name), c.data_type.trim());
    if c.auto_increment && kind == DbKind::Postgres {
        s.push_str(" GENERATED BY DEFAULT AS IDENTITY");
    }
    if !c.nullable {
        s.push_str(" NOT NULL");
    }
    if let Some(d) = c.default.as_deref().filter(|d| !d.trim().is_empty()) {
        s.push_str(&format!(" DEFAULT {}", d.trim()));
    }
    if c.auto_increment && kind == DbKind::Mysql {
        s.push_str(" AUTO_INCREMENT");
    }
    if kind == DbKind::Mysql
        && let Some(cm) = c.comment.as_deref().filter(|x| !x.is_empty())
    {
        s.push_str(&format!(" COMMENT {}", lit(kind, cm)));
    }
    s
}

fn fk_sql(kind: DbKind, f: &ForeignKeyDef) -> String {
    let mut s = format!(
        "CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})",
        q(kind, &f.name),
        list(kind, &f.columns),
        rel(kind, &f.ref_schema, &f.ref_table),
        list(kind, &f.ref_columns)
    );
    for (word, v) in [("ON DELETE", &f.on_delete), ("ON UPDATE", &f.on_update)] {
        let v = v.trim().to_uppercase();
        if !v.is_empty() && v != "NO ACTION" {
            s.push_str(&format!(" {word} {v}"));
        }
    }
    s
}

fn index_sql(kind: DbKind, t: &TableDef, i: &IndexDef) -> String {
    format!("CREATE {}INDEX {} ON {} ({})", if i.unique { "UNIQUE " } else { "" }, q(kind, &i.name), rel(kind, &t.schema, &t.name), list(kind, &i.columns))
}

fn check(kind: DbKind, t: &TableDef) -> AppResult<()> {
    if !matches!(kind, DbKind::Postgres | DbKind::Mysql) {
        return Err(AppError::Msg("Creating and modifying tables works for PostgreSQL and MySQL".into()));
    }
    if t.name.trim().is_empty() {
        return Err(AppError::Msg("Give the table a name".into()));
    }
    if t.columns.is_empty() {
        return Err(AppError::Msg("Add at least one column".into()));
    }
    let mut seen = std::collections::HashSet::new();
    for c in &t.columns {
        if c.name.trim().is_empty() || c.data_type.trim().is_empty() {
            return Err(AppError::Msg("Every column needs a name and a type".into()));
        }
        if !seen.insert(c.name.to_lowercase()) {
            return Err(AppError::Msg(format!("Column \"{}\" appears twice", c.name)));
        }
    }
    for k in &t.primary_key {
        if !t.columns.iter().any(|c| c.name == *k) {
            return Err(AppError::Msg(format!("Primary key column \"{k}\" is not in the table")));
        }
    }
    for i in t.indexes.iter().filter(|i| i.definition.is_none()) {
        if i.name.trim().is_empty() || i.columns.is_empty() {
            return Err(AppError::Msg("Every index needs a name and columns".into()));
        }
    }
    for f in &t.foreign_keys {
        if f.name.trim().is_empty() || f.columns.is_empty() || f.ref_table.trim().is_empty() || f.columns.len() != f.ref_columns.len() {
            return Err(AppError::Msg(format!("Foreign key \"{}\" needs a name, columns and as many referenced columns", f.name)));
        }
    }
    Ok(())
}

/// CREATE TABLE (+ 인덱스 · PG 설명)
pub fn create_table_sql(kind: DbKind, t: &TableDef) -> AppResult<Vec<String>> {
    check(kind, t)?;
    let mut parts: Vec<String> = t.columns.iter().map(|c| format!("    {}", column_sql(kind, c))).collect();
    if !t.primary_key.is_empty() {
        parts.push(format!("    PRIMARY KEY ({})", list(kind, &t.primary_key)));
    }
    for f in &t.foreign_keys {
        parts.push(format!("    {}", fk_sql(kind, f)));
    }
    let mut head = format!("CREATE TABLE {} (\n{}\n)", rel(kind, &t.schema, &t.name), parts.join(",\n"));
    if kind == DbKind::Mysql
        && let Some(cm) = t.comment.as_deref().filter(|x| !x.is_empty())
    {
        head.push_str(&format!(" COMMENT = {}", lit(kind, cm)));
    }
    let mut out = vec![head];
    out.extend(t.indexes.iter().filter(|i| i.definition.is_none()).map(|i| index_sql(kind, t, i)));
    if kind == DbKind::Postgres {
        out.extend(pg_comments(t, None));
    }
    Ok(out)
}

/// PG: 바뀐 설명 (before 가 없으면 있는 것 전부)
fn pg_comments(t: &TableDef, before: Option<&TableDef>) -> Vec<String> {
    let k = DbKind::Postgres;
    let r = rel(k, &t.schema, &t.name);
    let mut out = vec![];
    let val = |c: &Option<String>| c.as_deref().filter(|x| !x.is_empty()).map(|x| lit(k, x)).unwrap_or_else(|| "NULL".into());
    if before.map(|b| b.comment.clone().filter(|x| !x.is_empty())) != Some(t.comment.clone().filter(|x| !x.is_empty())) && (before.is_some() || t.comment.as_deref().is_some_and(|x| !x.is_empty())) {
        out.push(format!("COMMENT ON TABLE {r} IS {}", val(&t.comment)));
    }
    for c in &t.columns {
        let old = before.and_then(|b| c.orig.as_ref().and_then(|o| b.columns.iter().find(|x| x.name == *o))).map(|x| x.comment.clone().filter(|v| !v.is_empty()));
        let new = c.comment.clone().filter(|v| !v.is_empty());
        if (old.is_some() && old != Some(new.clone())) || (old.is_none() && new.is_some()) {
            out.push(format!("COMMENT ON COLUMN {r}.{} IS {}", q(k, &c.name), val(&c.comment)));
        }
    }
    out
}

/// before → after 로 바꾸는 ALTER 문장들 (바뀐 것이 없으면 빈 목록)
pub fn alter_table_sql(kind: DbKind, before: &TableDef, after: &TableDef) -> AppResult<Vec<String>> {
    check(kind, after)?;
    let mut out = vec![];
    let my = kind == DbKind::Mysql;
    // 1. 이름
    let mut t = after.clone();
    t.name = before.name.clone();
    if after.name != before.name {
        out.push(if my {
            format!("RENAME TABLE {} TO {}", rel(kind, &before.schema, &before.name), rel(kind, &before.schema, &after.name))
        } else {
            format!("ALTER TABLE {} RENAME TO {}", rel(kind, &before.schema, &before.name), q(kind, &after.name))
        });
        t.name = after.name.clone();
    }
    let r = rel(kind, &t.schema, &t.name);
    // 이름만 바뀐 컬럼은 DB 가 PK · 인덱스 · FK 에서 같이 바꾼다 → 비교는 지금 이름으로 되돌려서
    let back = |cols: &[String]| -> Vec<String> { cols.iter().map(|c| after.columns.iter().find(|x| x.name == *c).and_then(|x| x.orig.clone()).unwrap_or_else(|| c.clone())).collect() };
    // 2. 지우거나 바뀐 FK · 인덱스 (컬럼을 바꾸기 전에). a = after 쪽, b = before 쪽
    let same_fk = |a: &ForeignKeyDef, b: &ForeignKeyDef| ForeignKeyDef { orig: None, columns: back(&a.columns), ..a.clone() } == ForeignKeyDef { orig: None, ..b.clone() };
    for f in &before.foreign_keys {
        if !after.foreign_keys.iter().any(|n| n.orig.as_deref() == Some(&f.name) && same_fk(n, f)) {
            out.push(if my { format!("ALTER TABLE {r} DROP FOREIGN KEY {}", q(kind, &f.name)) } else { format!("ALTER TABLE {r} DROP CONSTRAINT {}", q(kind, &f.name)) });
        }
    }
    let same_ix = |a: &IndexDef, b: &IndexDef| a.name == b.name && back(&a.columns) == b.columns && a.unique == b.unique;
    for i in &before.indexes {
        if !after.indexes.iter().any(|n| n.orig.as_deref() == Some(&i.name) && same_ix(n, i)) {
            out.push(match (my, i.constraint) {
                (true, _) => format!("DROP INDEX {} ON {r}", q(kind, &i.name)),
                (false, true) => format!("ALTER TABLE {r} DROP CONSTRAINT {}", q(kind, &i.name)),
                (false, false) => format!("DROP INDEX {}", rel(kind, &t.schema, &i.name)),
            });
        }
    }
    // 3. PK 가 바뀌면 먼저 지운다
    let pk_changed = before.primary_key != back(&after.primary_key);
    if pk_changed && !before.primary_key.is_empty() {
        out.push(if my {
            format!("ALTER TABLE {r} DROP PRIMARY KEY")
        } else {
            format!("ALTER TABLE {r} DROP CONSTRAINT {}", q(kind, before.primary_key_name.as_deref().unwrap_or(&format!("{}_pkey", before.name))))
        });
    }
    // 4. 컬럼: 지우기 · 바꾸기 · 더하기
    for c in &before.columns {
        if !after.columns.iter().any(|n| n.orig.as_deref() == Some(&c.name)) {
            out.push(format!("ALTER TABLE {r} DROP COLUMN {}", q(kind, &c.name)));
        }
    }
    for c in &after.columns {
        let Some(old) = c.orig.as_ref().and_then(|o| before.columns.iter().find(|x| x.name == *o)) else { continue };
        let norm = |x: &ColumnDef| ColumnDef { orig: None, default: x.default.clone().filter(|d| !d.trim().is_empty()), comment: x.comment.clone().filter(|d| !d.is_empty()), data_type: x.data_type.trim().to_string(), ..x.clone() };
        if norm(c) == norm(old) {
            continue;
        }
        if my {
            out.push(format!("ALTER TABLE {r} CHANGE COLUMN {} {}", q(kind, &old.name), column_sql(kind, c)));
            continue;
        }
        let col = q(kind, &c.name);
        if c.name != old.name {
            out.push(format!("ALTER TABLE {r} RENAME COLUMN {} TO {col}", q(kind, &old.name)));
        }
        if c.data_type.trim() != old.data_type.trim() {
            out.push(format!("ALTER TABLE {r} ALTER COLUMN {col} TYPE {} USING {col}::{}", c.data_type.trim(), c.data_type.trim()));
        }
        if c.auto_increment != old.auto_increment {
            out.push(if c.auto_increment { format!("ALTER TABLE {r} ALTER COLUMN {col} ADD GENERATED BY DEFAULT AS IDENTITY") } else { format!("ALTER TABLE {r} ALTER COLUMN {col} DROP IDENTITY") });
        }
        if c.nullable != old.nullable {
            out.push(format!("ALTER TABLE {r} ALTER COLUMN {col} {} NOT NULL", if c.nullable { "DROP" } else { "SET" }));
        }
        if norm(c).default != norm(old).default {
            out.push(match norm(c).default {
                Some(d) => format!("ALTER TABLE {r} ALTER COLUMN {col} SET DEFAULT {}", d.trim()),
                None => format!("ALTER TABLE {r} ALTER COLUMN {col} DROP DEFAULT"),
            });
        }
    }
    for c in after.columns.iter().filter(|c| c.orig.is_none()) {
        out.push(format!("ALTER TABLE {r} ADD COLUMN {}", column_sql(kind, c)));
    }
    // 5. PK · 인덱스 · FK 더하기
    if pk_changed && !after.primary_key.is_empty() {
        out.push(format!("ALTER TABLE {r} ADD PRIMARY KEY ({})", list(kind, &after.primary_key)));
    }
    for i in after.indexes.iter().filter(|i| i.definition.is_none()) {
        if !before.indexes.iter().any(|b| i.orig.as_deref() == Some(&b.name) && same_ix(i, b)) {
            out.push(index_sql(kind, &t, i));
        }
    }
    for f in &after.foreign_keys {
        if !before.foreign_keys.iter().any(|b| f.orig.as_deref() == Some(&b.name) && same_fk(f, b)) {
            out.push(format!("ALTER TABLE {r} ADD {}", fk_sql(kind, f)));
        }
    }
    // 6. 설명
    if my {
        if before.comment.clone().filter(|x| !x.is_empty()) != after.comment.clone().filter(|x| !x.is_empty()) {
            out.push(format!("ALTER TABLE {r} COMMENT = {}", lit(kind, after.comment.as_deref().unwrap_or(""))));
        }
    } else {
        out.extend(pg_comments(&t, Some(before)));
    }
    Ok(out)
}

/// New ▸ Database · Schema · View · Materialized View · Sequence
pub fn new_object_sql(kind: DbKind, o: &NewObject) -> AppResult<Vec<String>> {
    if !matches!(kind, DbKind::Postgres | DbKind::Mysql) {
        return Err(AppError::Msg("Works for PostgreSQL and MySQL".into()));
    }
    let need = |s: &str, what: &str| if s.trim().is_empty() { Err(AppError::Msg(format!("Give the {what} a name"))) } else { Ok(()) };
    let my = kind == DbKind::Mysql;
    Ok(vec![match o {
        NewObject::Database { name, charset } => {
            need(name, "database")?;
            let cs = charset.trim();
            match (my, cs.is_empty()) {
                (_, true) => format!("CREATE DATABASE {}", q(kind, name)),
                (true, false) => format!("CREATE DATABASE {} CHARACTER SET {cs}", q(kind, name)),
                (false, false) => format!("CREATE DATABASE {} ENCODING {}", q(kind, name), lit(kind, cs)),
            }
        }
        NewObject::Schema { name } => {
            need(name, "schema")?;
            if my {
                return Err(AppError::Msg("In MySQL a schema is a database — use New › Database".into()));
            }
            format!("CREATE SCHEMA {}", q(kind, name))
        }
        NewObject::View { schema, name, query, materialized } => {
            need(name, "view")?;
            if query.trim().is_empty() {
                return Err(AppError::Msg("Write the view's SELECT".into()));
            }
            if *materialized && my {
                return Err(AppError::Msg("MySQL has no materialized views".into()));
            }
            format!("CREATE {}VIEW {} AS\n{}", if *materialized { "MATERIALIZED " } else { "" }, rel(kind, schema, name), query.trim().trim_end_matches(';'))
        }
        NewObject::Sequence { schema, name, start, increment } => {
            need(name, "sequence")?;
            if my {
                return Err(AppError::Msg("MySQL has no sequences — use AUTO_INCREMENT on a column".into()));
            }
            let mut s = format!("CREATE SEQUENCE {}", rel(kind, schema, name));
            if let Some(i) = increment {
                s.push_str(&format!(" INCREMENT BY {i}"));
            }
            if let Some(v) = start {
                s.push_str(&format!(" START WITH {v}"));
            }
            s
        }
    }])
}

/// Rename… (⇧F6): table · view · materialized view · sequence · schema · database
pub fn rename_sql(kind: DbKind, what: &str, schema: &str, old: &str, new: &str) -> AppResult<String> {
    if new.trim().is_empty() {
        return Err(AppError::Msg("Give a new name".into()));
    }
    let my = kind == DbKind::Mysql;
    Ok(match (what, my) {
        ("table" | "partitioned" | "view", true) => format!("RENAME TABLE {} TO {}", rel(kind, schema, old), rel(kind, schema, new)),
        ("table" | "partitioned" | "foreign", false) => format!("ALTER TABLE {} RENAME TO {}", rel(kind, schema, old), q(kind, new)),
        ("view", false) => format!("ALTER VIEW {} RENAME TO {}", rel(kind, schema, old), q(kind, new)),
        ("matview", false) => format!("ALTER MATERIALIZED VIEW {} RENAME TO {}", rel(kind, schema, old), q(kind, new)),
        ("sequence", false) => format!("ALTER SEQUENCE {} RENAME TO {}", rel(kind, schema, old), q(kind, new)),
        ("schema", false) => format!("ALTER SCHEMA {} RENAME TO {}", q(kind, old), q(kind, new)),
        ("db", false) => format!("ALTER DATABASE {} RENAME TO {}", q(kind, old), q(kind, new)),
        _ => return Err(AppError::Msg(format!("Renaming a {what} is not supported here"))),
    })
}

// ───────── 지금 구조 읽기 ─────────

fn action(c: &str) -> String {
    match c {
        "r" | "RESTRICT" => "RESTRICT",
        "c" | "CASCADE" => "CASCADE",
        "n" | "SET NULL" => "SET NULL",
        "d" | "SET DEFAULT" => "SET DEFAULT",
        _ => "NO ACTION",
    }
    .into()
}

async fn load(pool: &Pool, schema: &str, table: &str) -> AppResult<TableDef> {
    let mut t = TableDef { schema: schema.into(), name: table.into(), ..Default::default() };
    match pool {
        Pool::Pg(p) => {
            const REL: &str = "(SELECT c.oid FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = $1 AND c.relname = $2)";
            let cols: Vec<(String, String, bool, Option<String>, bool, Option<String>)> = sqlx::query_as(&format!(
                "SELECT a.attname::text, format_type(a.atttypid, a.atttypmod), NOT a.attnotnull, pg_get_expr(d.adbin, d.adrelid), a.attidentity <> '', col_description(a.attrelid, a.attnum) \
                 FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum \
                 WHERE a.attrelid = {REL} AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum"
            ))
            .bind(schema)
            .bind(table)
            .fetch_all(p)
            .await?;
            if cols.is_empty() {
                return Err(AppError::Msg(format!("Couldn't find table {schema}.{table}")));
            }
            t.columns = cols.into_iter().map(|(name, data_type, nullable, default, auto_increment, comment)| ColumnDef { orig: Some(name.clone()), name, data_type, nullable, default, auto_increment, comment }).collect();
            t.comment = sqlx::query_scalar::<_, Option<String>>(&format!("SELECT obj_description({REL}, 'pg_class')")).bind(schema).bind(table).fetch_one(p).await?;
            let pk: Option<(String, Vec<String>)> = sqlx::query_as(&format!(
                "SELECT c.conname::text, array(SELECT a.attname::text FROM unnest(c.conkey) WITH ORDINALITY k(n, o) JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.n ORDER BY k.o) \
                 FROM pg_constraint c WHERE c.conrelid = {REL} AND c.contype = 'p'"
            ))
            .bind(schema)
            .bind(table)
            .fetch_optional(p)
            .await?;
            if let Some((name, cols)) = pk {
                t.primary_key_name = Some(name);
                t.primary_key = cols;
            }
            // 인덱스 (PK 빼고). UNIQUE 제약이 쓰는 것은 constraint. 식 · 조건 인덱스는 정의 글만
            let idx: Vec<(String, bool, bool, Vec<String>, bool, String)> = sqlx::query_as(&format!(
                "SELECT i.relname::text, ix.indisunique, EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = ix.indexrelid AND c.contype = 'u'), \
                        array(SELECT a.attname::text FROM unnest(ix.indkey) WITH ORDINALITY k(n, o) JOIN pg_attribute a ON a.attrelid = ix.indrelid AND a.attnum = k.n ORDER BY k.o), \
                        ix.indexprs IS NOT NULL OR ix.indpred IS NOT NULL, pg_get_indexdef(ix.indexrelid) \
                 FROM pg_index ix JOIN pg_class i ON i.oid = ix.indexrelid WHERE ix.indrelid = {REL} AND NOT ix.indisprimary ORDER BY i.relname"
            ))
            .bind(schema)
            .bind(table)
            .fetch_all(p)
            .await?;
            t.indexes = idx
                .into_iter()
                .map(|(name, unique, constraint, columns, complex, def)| IndexDef { orig: Some(name.clone()), name, columns: if complex { vec![] } else { columns }, unique, constraint, definition: complex.then_some(def) })
                .collect();
            let fks: Vec<(String, Vec<String>, String, String, Vec<String>, String, String)> = sqlx::query_as(&format!(
                "SELECT c.conname::text, \
                   array(SELECT a.attname::text FROM unnest(c.conkey) WITH ORDINALITY k(n, o) JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.n ORDER BY k.o), \
                   rn.nspname::text, rc.relname::text, \
                   array(SELECT a.attname::text FROM unnest(c.confkey) WITH ORDINALITY k(n, o) JOIN pg_attribute a ON a.attrelid = c.confrelid AND a.attnum = k.n ORDER BY k.o), \
                   c.confdeltype::text, c.confupdtype::text \
                 FROM pg_constraint c JOIN pg_class rc ON rc.oid = c.confrelid JOIN pg_namespace rn ON rn.oid = rc.relnamespace \
                 WHERE c.conrelid = {REL} AND c.contype = 'f' ORDER BY c.conname"
            ))
            .bind(schema)
            .bind(table)
            .fetch_all(p)
            .await?;
            t.foreign_keys = fks
                .into_iter()
                .map(|(name, columns, ref_schema, ref_table, ref_columns, del, upd)| ForeignKeyDef { orig: Some(name.clone()), name, columns, ref_schema, ref_table, ref_columns, on_delete: action(&del), on_update: action(&upd) })
                .collect();
        }
        Pool::My(p) => {
            let cols: Vec<(String, String, String, Option<String>, String, String)> = sqlx::query_as(
                "SELECT CAST(COLUMN_NAME AS CHAR), CAST(COLUMN_TYPE AS CHAR), CAST(IS_NULLABLE AS CHAR), CAST(COLUMN_DEFAULT AS CHAR), CAST(EXTRA AS CHAR), CAST(COLUMN_COMMENT AS CHAR) \
                 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY ORDINAL_POSITION",
            )
            .bind(schema)
            .bind(table)
            .fetch_all(p)
            .await?;
            if cols.is_empty() {
                return Err(AppError::Msg(format!("Couldn't find table {schema}.{table}")));
            }
            t.columns = cols
                .into_iter()
                .map(|(name, data_type, nullable, default, extra, comment)| {
                    let extra = extra.to_lowercase();
                    // information_schema 의 기본값은 따옴표가 없다: 식이 아니면 글로 감싼다
                    let numeric = ["int", "decimal", "float", "double", "bit", "year"].iter().any(|n| data_type.to_lowercase().starts_with(n));
                    let expr = extra.contains("default_generated") || default.as_deref().is_some_and(|d| d.to_uppercase().starts_with("CURRENT_TIMESTAMP"));
                    let default = default.map(|d| if numeric || expr { d } else { lit(DbKind::Mysql, &d) });
                    ColumnDef { orig: Some(name.clone()), name, data_type, nullable: nullable == "YES", default, auto_increment: extra.contains("auto_increment"), comment: Some(comment).filter(|c| !c.is_empty()) }
                })
                .collect();
            t.comment = sqlx::query_scalar::<_, Option<String>>("SELECT CAST(TABLE_COMMENT AS CHAR) FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ?")
                .bind(schema)
                .bind(table)
                .fetch_one(p)
                .await?
                .filter(|c| !c.is_empty());
            let stats: Vec<(String, i64, Option<String>, i64)> = sqlx::query_as(
                "SELECT CAST(INDEX_NAME AS CHAR), CAST(NON_UNIQUE AS SIGNED), CAST(COLUMN_NAME AS CHAR), CAST(SEQ_IN_INDEX AS SIGNED) FROM information_schema.STATISTICS \
                 WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY INDEX_NAME, SEQ_IN_INDEX",
            )
            .bind(schema)
            .bind(table)
            .fetch_all(p)
            .await?;
            for (name, non_unique, col, _) in stats {
                if name == "PRIMARY" {
                    t.primary_key.extend(col);
                    t.primary_key_name = Some(name);
                    continue;
                }
                match t.indexes.iter_mut().find(|i| i.name == name) {
                    Some(i) => match col {
                        Some(c) => i.columns.push(c),
                        None => i.definition = Some(format!("{name} (expression)")),
                    },
                    None => t.indexes.push(IndexDef { orig: Some(name.clone()), definition: col.is_none().then(|| format!("{name} (expression)")), columns: col.into_iter().collect(), name, unique: non_unique == 0, constraint: false }),
                }
            }
            let fks: Vec<(String, String, String, String, String, String, String)> = sqlx::query_as(
                "SELECT CAST(k.CONSTRAINT_NAME AS CHAR), CAST(k.COLUMN_NAME AS CHAR), CAST(k.REFERENCED_TABLE_SCHEMA AS CHAR), CAST(k.REFERENCED_TABLE_NAME AS CHAR), \
                        CAST(k.REFERENCED_COLUMN_NAME AS CHAR), CAST(r.DELETE_RULE AS CHAR), CAST(r.UPDATE_RULE AS CHAR) \
                 FROM information_schema.KEY_COLUMN_USAGE k JOIN information_schema.REFERENTIAL_CONSTRAINTS r \
                   ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME AND r.TABLE_NAME = k.TABLE_NAME \
                 WHERE k.TABLE_SCHEMA = ? AND k.TABLE_NAME = ? AND k.REFERENCED_TABLE_NAME IS NOT NULL ORDER BY k.CONSTRAINT_NAME, k.ORDINAL_POSITION",
            )
            .bind(schema)
            .bind(table)
            .fetch_all(p)
            .await?;
            for (name, col, rs, rt, rc, del, upd) in fks {
                match t.foreign_keys.iter_mut().find(|f| f.name == name) {
                    Some(f) => {
                        f.columns.push(col);
                        f.ref_columns.push(rc);
                    }
                    None => t.foreign_keys.push(ForeignKeyDef { orig: Some(name.clone()), name, columns: vec![col], ref_schema: rs, ref_table: rt, ref_columns: vec![rc], on_delete: action(&del), on_update: action(&upd) }),
                }
            }
            // FK 가 쓰는 인덱스 (MySQL 이 FK 이름으로 만든 것) 는 FK 와 같이 다룬다
            let fk_names: Vec<String> = t.foreign_keys.iter().map(|f| f.name.clone()).collect();
            t.indexes.retain(|i| !fk_names.contains(&i.name));
        }
        _ => return Err(AppError::Msg("Modifying tables works for PostgreSQL and MySQL".into())),
    }
    Ok(t)
}

impl AppState {
    /// Modify Table…: 지금 구조
    pub async fn table_def(&self, id: String, schema: String, table: String) -> AppResult<TableDef> {
        load(&ensure_pool(self, &id).await?, &schema, &table).await
    }

    /// 미리보기: before 가 있으면 ALTER, 없으면 CREATE
    pub fn table_ddl(&self, id: String, before: Option<TableDef>, after: TableDef) -> AppResult<Vec<String>> {
        let kind = self.kind_of(&id)?;
        match before {
            Some(b) => alter_table_sql(kind, &b, &after),
            None => create_table_sql(kind, &after),
        }
    }

    pub fn new_object_ddl(&self, id: String, object: NewObject) -> AppResult<Vec<String>> {
        new_object_sql(self.kind_of(&id)?, &object)
    }

    pub fn rename_ddl(&self, id: String, what: String, schema: String, old: String, new: String) -> AppResult<String> {
        rename_sql(self.kind_of(&id)?, &what, &schema, &old, &new)
    }

    /// 만든 DDL 실행: PG 는 한 트랜잭션 (실패하면 하나도 안 바뀐다). CREATE / DROP DATABASE 는 트랜잭션 밖에서 하나씩.
    /// MySQL 은 DDL 이 바로 반영되므로 하나씩 (실패하면 앞의 것은 이미 바뀌었다고 알린다)
    pub async fn run_ddl(&self, id: String, statements: Vec<String>) -> AppResult<()> {
        let kind = self.kind_of(&id)?;
        let outside = |s: &str| {
            let l = s.trim_start().to_uppercase();
            l.starts_with("CREATE DATABASE") || l.starts_with("ALTER DATABASE") || l.starts_with("DROP DATABASE")
        };
        if kind == DbKind::Postgres && !statements.iter().any(|s| outside(s)) {
            self.execute_batch(id, statements, false).await?;
            return Ok(());
        }
        for (i, s) in statements.iter().enumerate() {
            if let Err(e) = self.run_query(id.clone(), s.clone(), Some(1), None).await {
                return Err(if i > 0 { AppError::Msg(format!("{e}\n(The first {i} statement(s) were already applied)")) } else { e });
            }
        }
        Ok(())
    }
}

