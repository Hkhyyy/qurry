/// A serial key and an identity key whose sequence is behind the rows added with their keys (#167): Submit's new row fails on a
/// duplicate key, its error says which (the server's DETAIL), sequence_behind offers the setval, and after it the row goes in
#[tokio::test]
#[ignore]
async fn postgres_sequence_behind_hint_fixes_submit() {
    use qurry_shared::errors::sequence_behind;
    let e = std::env::var("QURRY_TEST_PG").expect("QURRY_TEST_PG=host:port:user:db");
    let p: Vec<&str> = e.split(':').collect();
    let dir = tempfile::Builder::new().prefix("qurry-grid-seq-").tempdir().unwrap();
    let st = qurry_core::open_state(Some(dir.path().to_path_buf())).unwrap();
    st.save_connection(cfg("postgres", p[0], p[1], p[2], p[3]), None, None).await.unwrap();
    for (table, key) in [("grid_seq_serial", "id serial"), ("Grid Seq Identity", "\"Id\" int GENERATED BY DEFAULT AS IDENTITY")] {
        let col = if table.starts_with("Grid") { "Id" } else { "id" };
        let rel = format!("public.{}", qurry_shared::sql::quote_ident(DbKind::Postgres, table));
        q(&st, &format!("DROP TABLE IF EXISTS {rel}")).await;
        q(&st, &format!("CREATE TABLE {rel} ({key} PRIMARY KEY, name text)")).await;
        q(&st, &format!("INSERT INTO {rel} VALUES (1, 'a'), (2, 'b')")).await;
        let filled: Vec<String> = st.table_detail(ID.into(), "public".into(), table.into()).await.unwrap().columns.into_iter().filter(|c| c.auto_increment).map(|c| c.name).collect();
        assert_eq!(filled, [col], "{table}");
        let to = EditTarget { schema: "public".into(), table: table.into(), pk: vec![col.into()], columns: vec![col.into(), "name".into()] };
        let stmts = edit_statements(DbKind::Postgres, &to, &[], &BTreeMap::new(), &BTreeSet::new(), &[BTreeMap::from([(1, Some("new".into()))])]).unwrap();
        let err = st.submit_edits(ID.into(), None, stmts.clone()).await.expect_err("the sequence gives 1 again").to_string();
        assert!(err.contains(&format!("Key ({})=(1) already exists.", qurry_shared::sql::quote_ident(DbKind::Postgres, col))), "{err}");
        let fix = sequence_behind(DbKind::Postgres, &err, "public", table, &filled).unwrap_or_else(|| panic!("no hint: {err}"));
        assert!(sequence_behind(DbKind::Postgres, &err, "public", table, &[]).is_none());
        q(&st, &fix.sql).await;
        st.submit_edits(ID.into(), None, stmts).await.unwrap_or_else(|e| panic!("{}: {e}", fix.sql));
        assert_eq!(q(&st, &format!("SELECT name FROM {rel} WHERE {} = 3", qurry_shared::sql::quote_ident(DbKind::Postgres, col))).await, [[Value::String("new".into())]], "{table}");
        q(&st, &format!("DROP TABLE {rel}")).await;
    }
}
